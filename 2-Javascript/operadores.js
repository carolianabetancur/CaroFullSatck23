//Operadores aritméticos
console.log(2 + 2);
console.log(2 - 2);
console.log(2 * 2);
console.log(2 / 2);
console.log(2 % 2); //Módulo, nos entrega el residuo de la división
console.log(2 ** 2); //Potencia 2 a la 2

//Operadores booleanos. Permiten comparar elementos lógicos. Verdadero, falso o negación
console.log(4 > 2);
console.log(3 < 2);
console.log(3 == 2);
console.log(false);
console.log(true);
console.log(!true);

//Operadores de relación: para relacionar dos variables o dos valores
console.log(4 >= 2);
console.log(3 <= 2);
console.log(3 === 2);
console.log(3 !== 2);

//Operadores de asignación
const a = 1;
const b = 2;
console.log(a < b);
